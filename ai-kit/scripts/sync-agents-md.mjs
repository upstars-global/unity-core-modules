// sync-agents-md — generates AGENTS.md from the toolkit's rule files plus whatever
// repository-local context the repository already carries.
//
// Why generate it: Claude Code receives the rule index through the SessionStart hook, but Codex
// and other agents only read AGENTS.md. Writing it by hand in three repositories is how the two
// instruction sets drifted apart in the first place.
//
// CLI:
//   node ai-kit/scripts/sync-agents-md.mjs                 # write AGENTS.md in the current repo
//   node ai-kit/scripts/sync-agents-md.mjs --check         # exit 1 if the file is out of date
//   node ai-kit/scripts/sync-agents-md.mjs --role app      # override the detected role
//   node ai-kit/scripts/sync-agents-md.mjs --out FILE      # write somewhere else
//
// In a consuming repository:
//   node node_modules/unity-core-modules/ai-kit/scripts/sync-agents-md.mjs

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { appliesToRole, readRules, relativeFromCwd, repoRole } from "./rules.mjs";

function arg (name, fallback) {
    const index = process.argv.indexOf(`--${ name }`);

    return index !== -1 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const cwd = process.cwd();
const role = arg("role", repoRole(cwd));
const outFile = resolve(cwd, arg("out", "AGENTS.md"));
const checkOnly = process.argv.includes("--check");
const invocation = relativeFromCwd(fileURLToPath(import.meta.url), cwd);

function repoName () {
    try {
        return JSON.parse(readFileSync(join(cwd, "package.json"), "utf8")).name ?? "this repository";
    } catch {
        return "this repository";
    }
}

// First markdown heading of a file, used as its title in the listing.
function title (path, fallback) {
    try {
        const heading = readFileSync(path, "utf8")
            .split("\n")
            .find((line) => /^#{1,3}\s+\S/.test(line));

        return heading ? heading.replace(/^#+\s+/, "").trim() : fallback;
    } catch {
        return fallback;
    }
}

// Repository-local markdown an agent should know about, in the places these repositories use.
function localDocs () {
    const found = [];

    for (const dir of [ "docs/ai-context", "guides-md", "guids-md" ]) {
        const abs = join(cwd, dir);
        if (!existsSync(abs)) {
            continue;
        }

        for (const file of readdirSync(abs).filter((name) => name.endsWith(".md")).sort()) {
            found.push({
                path: `${ dir }/${ file }`,
                title: title(join(abs, file), file.replace(/\.md$/, "")),
            });
        }
    }

    return found;
}

const rules = readRules().filter((rule) => appliesToRole(rule, role));
const docs = localDocs();

const body = [
    "# Codex instructions",
    "",
    `<!-- Generated by unity-ai: node ${ invocation }`,
    "     Edit the rule files in unity-core-modules, not this file. -->",
    "",
    `Repository: \`${ repoName() }\` (role: ${ role }).`,
    "",
    "## Shared rules",
    "",
    "Read the file that covers the area you are changing. These live in the shared package, so the",
    "same rules apply in every Unity front-end repository.",
    "",
    ...rules.map((rule) => `- \`${ relativeFromCwd(rule.path, cwd) }\` — ${ rule.description }`),
    "",
];

if (docs.length > 0) {
    body.push(
        "## Repository-local context",
        "",
        "Specific to this repository, and it wins over the shared rules where they disagree.",
        "",
        ...docs.map((doc) => `- \`${ doc.path }\` — ${ doc.title }`),
        "",
    );
}

body.push(
    "## Hard rules",
    "",
    "- Keep changes minimal and inside the requested scope.",
    "- Follow the pattern already used in the file you are editing.",
    "- Add tests for meaningful changed logic.",
    "- Style is enforced by `unity-eslint-config`; run the repository's lint script instead of",
    "  hand-formatting.",
    "",
);

const generated = body.join("\n");
const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";

if (checkOnly) {
    const ok = current === generated;
    process.stdout.write(ok ? "AGENTS.md is up to date\n" : "AGENTS.md is out of date — run sync-agents-md.mjs\n");
    process.exit(ok ? 0 : 1);
}

if (current === generated) {
    process.stdout.write("AGENTS.md unchanged\n");
    process.exit(0);
}

writeFileSync(outFile, generated);
process.stdout.write(`wrote ${ relativeFromCwd(outFile, cwd) }: ${ rules.length } shared rules, ${ docs.length } local docs\n`);
